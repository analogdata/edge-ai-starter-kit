"""
Train a tiny keyword-spotting model and export it for the ESP32.

    python train.py                 # real data (downloads Speech Commands)
    python train.py --synthetic     # 1-minute pipeline check, fake data

Output (written into ../firmware/main):
    model_data.cc   the int8 model as a C array
    kws_config.h    labels + sizes the firmware needs
Also saves kws_int8.tflite next to this script.
"""
import argparse
import os

import numpy as np
import tensorflow as tf

import dataset as D
import features as F

HERE = os.path.dirname(os.path.abspath(__file__))
FW_DIR = os.path.join(HERE, "..", "firmware", "main")


def build_model(n_classes):
    """Small depthwise-separable CNN (~20k parameters). Only uses ops that TFLite Micro supports."""
    L = tf.keras.layers
    inp = tf.keras.Input(shape=(F.NUM_FRAMES, F.NUM_MEL, 1))
    x = L.Conv2D(24, 3, strides=2, padding="same", use_bias=False)(inp)
    x = L.ReLU()(L.BatchNormalization(momentum=0.9)(x))
    for ch in (32, 48, 48):
        x = L.DepthwiseConv2D(3, padding="same", use_bias=False)(x)
        x = L.ReLU()(L.BatchNormalization(momentum=0.9)(x))
        x = L.Conv2D(ch, 1, use_bias=False)(x)
        x = L.ReLU()(L.BatchNormalization(momentum=0.9)(x))
    x = L.GlobalAveragePooling2D()(x)
    x = L.Dropout(0.2)(x)
    out = L.Dense(n_classes, activation="softmax")(x)
    return tf.keras.Model(inp, out)


def to_int8_tflite(model, rep_x):
    def rep():
        for i in range(min(300, len(rep_x))):
            yield [rep_x[i:i + 1]]
    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = rep
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    return conv.convert()


def tflite_accuracy(tflite_bytes, x, y):
    it = tf.lite.Interpreter(model_content=tflite_bytes)
    it.allocate_tensors()
    i_det, o_det = it.get_input_details()[0], it.get_output_details()[0]
    s, zp = i_det["quantization"]
    correct = 0
    for xi, yi in zip(x, y):
        q = np.clip(np.round(xi / s + zp), -128, 127).astype(np.int8)[None]
        it.set_tensor(i_det["index"], q)
        it.invoke()
        correct += int(np.argmax(it.get_tensor(o_det["index"])[0]) == yi)
    return correct / len(x)


def tflite_ops(tflite_bytes):
    it = tf.lite.Interpreter(model_content=tflite_bytes)
    return sorted({d["op_name"] for d in it._get_ops_details()})


def write_c_files(tflite_bytes, labels, ops):
    os.makedirs(FW_DIR, exist_ok=True)
    with open(os.path.join(FW_DIR, "model_data.cc"), "w") as f:
        f.write("// AUTO-GENERATED by train/train.py. Do not edit.\n")
        f.write('#include "model_data.h"\n\nalignas(16) const unsigned char g_kws_model[] = {\n')
        for i in range(0, len(tflite_bytes), 12):
            f.write("  " + ", ".join(f"0x{b:02x}" for b in tflite_bytes[i:i + 12]) + ",\n")
        f.write(f"}};\nconst unsigned int g_kws_model_len = {len(tflite_bytes)};\n")
    with open(os.path.join(FW_DIR, "kws_config.h"), "w") as f:
        f.write("// AUTO-GENERATED by train/train.py. Do not edit.\n#pragma once\n")
        f.write(f"#define KWS_NUM_LABELS {len(labels)}\n")
        f.write("static const char *const KWS_LABELS[KWS_NUM_LABELS] = {"
                + ", ".join(f'"{l}"' for l in labels) + "};\n")
        f.write(f"// Ops the model needs: {', '.join(ops)}\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--synthetic", action="store_true", help="fake data, pipeline check only")
    ap.add_argument("--data-dir", default=os.path.join(HERE, "data"))
    ap.add_argument("--epochs", type=int, default=25)
    ap.add_argument("--batch", type=int, default=64)
    ap.add_argument("--aug-copies", type=int, default=1, help="noisy+shifted copies of train set")
    ap.add_argument("--max-per-class", type=int, default=None, help="limit clips per word (faster)")
    a = ap.parse_args()

    tf.keras.utils.set_random_seed(0)
    data = D.make_synthetic() if a.synthetic else D.load_speech_commands(
        a.data_dir, aug_copies=a.aug_copies, max_per_class=a.max_per_class)
    feats = {k: (F.log_mel(x)[..., None], y) for k, (x, y) in data.items()}
    (xtr, ytr), (xva, yva), (xte, yte) = feats["train"], feats["val"], feats["test"]

    model = build_model(len(D.LABELS))
    model.summary()
    model.compile(optimizer=tf.keras.optimizers.Adam(1e-3),
                  loss="sparse_categorical_crossentropy", metrics=["accuracy"])
    model.fit(xtr, ytr, validation_data=(xva, yva), epochs=a.epochs, batch_size=a.batch, verbose=2,
              callbacks=[tf.keras.callbacks.ReduceLROnPlateau(patience=3, factor=0.5),
                         tf.keras.callbacks.EarlyStopping(patience=6, restore_best_weights=True)])

    fp_acc = model.evaluate(xte, yte, verbose=0)[1]
    tfl = to_int8_tflite(model, xtr)
    q_acc = tflite_accuracy(tfl, xte, yte)
    ops = tflite_ops(tfl)
    print(f"\nTest accuracy  float: {fp_acc:.3f}   int8 (what the ESP32 runs): {q_acc:.3f}")
    print(f"Model size: {len(tfl) / 1024:.1f} KB   ops: {ops}")
    if a.synthetic:
        print("NOTE: synthetic data. This model does NOT understand speech. Train without --synthetic.")

    with open(os.path.join(HERE, "kws_int8.tflite"), "wb") as f:
        f.write(tfl)
    write_c_files(tfl, D.LABELS, ops)
    print("Wrote firmware/main/model_data.cc and kws_config.h")


if __name__ == "__main__":
    main()
